"""The Python Poseidon must equal the circuit's, bit for bit.

If it does not, roots computed here name batches the circuit will never accept,
and every proof fails for a reason that looks like anything but a hash
mismatch.  The reference values come from a witness generated by a compiled
circomlib ``Poseidon`` -- regenerate with
``scripts/gen_poseidon_reference.py``.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from zkfl.config import FIELD_PRIME
from zkfl.poseidon import poseidon, poseidon2, to_field

REFERENCE = Path(__file__).with_name("data") / "poseidon_reference.json"


def test_two_input_hash_matches_the_circuit():
    assert poseidon2(1, 2) == (
        7853200120776062878684798364095072458815029376092732009249414926327459813530
    )


def test_five_input_hash_matches_the_circuit():
    assert poseidon([7, 0, 12345678901234567890, 3, FIELD_PRIME - 1]) == (
        20837948755240029582330391946024003682408725819418676587023191778078218073870
    )


def test_generated_reference_vectors():
    if not REFERENCE.exists():
        pytest.skip("reference vectors absent; run scripts/gen_poseidon_reference.py")
    vectors = json.loads(REFERENCE.read_text())
    for case in vectors:
        assert poseidon(case["inputs"]) == int(case["out"]), case["inputs"]


def test_negative_inputs_are_reduced_the_way_circom_reduces_them():
    assert poseidon([to_field(-1)]) == poseidon([FIELD_PRIME - 1])


def test_hash_is_order_sensitive():
    assert poseidon2(1, 2) != poseidon2(2, 1)


def test_input_count_is_validated():
    with pytest.raises(ValueError):
        poseidon([])
    with pytest.raises(ValueError):
        poseidon(list(range(17)))
